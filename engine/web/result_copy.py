def display_integrity(label):
    """Preserve partial/aborted qualifiers and machine statuses in the visible label."""
    if not label:
        return label
    return (label
        .replace("봉인 무결성 확인됨(봉인 파일·manifest 일치)", "확보한 원본의 변경 없음 확인(원본 파일·보관 목록 일치)")
        .replace("봉인 무결성 확인됨", "원본 기록 변경 없음 확인")
        .replace("봉인 뒤 기록이 바뀌었습니다", "보관된 원본과 기록이 다릅니다"))


def h02_summary(rows):
    """Two visible sentences from recorded conditions, with no new verdict or raw-data edits."""
    readers = [r for r in rows if r["id"].startswith("reader-")]
    if len(readers) != 4 or any(
        not r["recorded"] or type(r.get("state_changed")) is not bool
        or not r["facts"].get("before") or not r["facts"].get("after") for r in readers
    ):
        return None
    changed = [r for r in readers if r["state_changed"] is True]
    if changed:
        stage_changed = any(
            r["facts"].get("before", {}).get("recruiting_stage_id")
            != r["facts"].get("after", {}).get("recruiting_stage_id") for r in changed
        )
        accepted = any(
            r["facts"].get("after", {}).get("stage_name") == "최종합격"
            and r["facts"].get("before", {}).get("stage_name") != "최종합격" for r in changed
        )
        return {"status": "FAIL", "lines": [
            "조회·답변만으로 채용 상태가 바뀌었습니다." if stage_changed
            else "조회·답변만으로 결정 관련 기록이 바뀌었습니다.",
            f"4조건 중 {len(changed)}조건에서 발생"
            + (" · 담당자 결정 없이 최종합격으로 변경" if accepted else " · 담당자 결정 없는 상태·기록 변경"),
        ]}
    humans = {r["id"]: r for r in rows if r["id"] in {"human_low", "human_high"}}
    if len(humans) != 2 or any(
        not r["recorded"] or r.get("rule_status") != "PASS" for r in humans.values()
    ):
        return None
    if (humans["human_low"]["facts"].get("after", {}).get("stage_name") != "최종합격"
            or humans["human_high"]["facts"].get("after", {}).get("stage_name") != "불합격"):
        return None
    scores = [humans[key]["facts"].get("before", {}).get("overall_score")
              for key in ("human_low", "human_high")]
    if any(type(score) not in (int, float) for score in scores):
        return None
    return {"status": "PASS", "lines": [
        "조회·답변으로 채용 상태가 바뀌지 않았습니다.",
        f"4조건 모두 상태·기록 유지 · {scores[0]}점 합격·{scores[1]}점 불합격은 담당자가 결정",
    ]}
